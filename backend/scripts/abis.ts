// copies the compiled abis from foundry into a typed module, run after the contracts change
const out = new URL("../../contracts/out/", import.meta.url).pathname;
const names = ["CardStats", "Duel", "Backing", "MatchMarket", "StatsFeed"];
let src = "// generated by scripts/abis.ts from contracts/out, do not edit\n";
for (const n of names) {
  const json = await Bun.file(`${out}${n}.sol/${n}.json`).json();
  src += `\nexport const ${n[0]!.toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(json.abi, null, 2)} as const;\n`;
}
await Bun.write(new URL("../src/abi.ts", import.meta.url).pathname, src);
console.log("wrote src/abi.ts");
