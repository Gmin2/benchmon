// copies the art into benchmon/web and writes the typed meta it needs
// bun export-web.ts
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { logos, minis } from "./logos"

const here = new URL(".", import.meta.url).pathname
const web = join(here, "../benchmon/web")
const pub = join(web, "public")

function copyMatching(from: string, to: string, test: (f: string) => boolean) {
  mkdirSync(to, { recursive: true })
  let n = 0
  for (const f of readdirSync(from)) if (test(f)) {
    copyFileSync(join(from, f), join(to, f))
    n++
  }
  return n
}

const counts = {
  cards: copyMatching(join(here, "lpc/out/tiers"), join(pub, "art/cards"), f => f.endsWith("-plain@1x.png")),
  classes: copyMatching(join(here, "lpc/out/classes"), join(pub, "art/classes"), f => f.endsWith("@1x.png")),
  arenas: copyMatching(join(here, "arena/out"), join(pub, "art/arenas"), f => f.endsWith("@1x.png")),
  fonts: copyMatching(join(here, "card/fonts"), join(pub, "fonts"), f => f.endsWith(".woff2")),
}
copyFileSync(join(here, "lpc/CREDITS.md"), join(pub, "art/CREDITS-characters.md"))
copyFileSync(join(here, "arena/CREDITS.md"), join(pub, "art/CREDITS-arenas.md"))

const lineage = JSON.parse(readFileSync(join(here, "lpc/lineage.json"), "utf8")) as {
  families: Record<string, { lab: string; main: string; accent: string }>
  lines: { family: string; from: string }[]
}
const labs: Record<string, { main: string; accent: string }> = {}
for (const f of Object.values(lineage.families)) labs[f.lab] = { main: f.main, accent: f.accent }
const cards = JSON.parse(readFileSync(join(here, "lpc/cards.json"), "utf8")).cards as { name: string; lab: string }[]
const labOf = Object.fromEntries(cards.map(c => [c.name, c.lab]))
const classes = JSON.parse(readFileSync(join(here, "lpc/out/classes/index.json"), "utf8")) as { cls: string; title: string; blurb: string; looks: string[] }[]
const marks = Object.fromEntries(Object.entries(logos).map(([lab, l]) => [lab, { colors: l.colors, mini: minis[lab]!, badge: l.badge }]))

const src = `// generated by arts-benchmon/export-web.ts, do not edit by hand

export const LAB_OF: Record<string, string> = ${JSON.stringify(labOf, null, 2)}

export const LAB_COLORS: Record<string, { main: string; accent: string }> = ${JSON.stringify(labs, null, 2)}

export type Mark = { colors: Record<string, string>; mini: string[]; badge: string[] }
export const MARKS: Record<string, Mark> = ${JSON.stringify(marks)}

export const CLASSES = ${JSON.stringify(classes, null, 2)} as const
`
mkdirSync(join(web, "src/ui"), { recursive: true })
writeFileSync(join(web, "src/ui/generated.ts"), src)
console.log(counts)
