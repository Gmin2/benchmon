type Px = { x: number; y: number; color: string }

export function pixels(grid: string[], colors: Record<string, string>, override?: string): Px[] {
  const out: Px[] = []
  grid.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === ".") return
      const color = override ?? colors[ch]
      if (color) out.push({ x, y, color })
    }),
  )
  return out
}

