// writes card/data.js from the live benchmon stats and the art pipeline outputs
// bun card/build-data.ts
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { logos, minis } from "../logos"

const here = new URL(".", import.meta.url).pathname
const stats = JSON.parse(readFileSync(join(here, "../../benchmon/backend/data/stats.json"), "utf8"))
const lineage = JSON.parse(readFileSync(join(here, "../lpc/lineage.json"), "utf8"))

type Raw = Record<string, number>
type StatCard = { id: number; name: string; lab: string; stats: number[]; power: number; raw: Raw }

const TYPES = ["reasoning", "speed", "cost"] as const
const labColors: Record<string, { main: string; accent: string }> = {}
for (const fam of Object.values(lineage.families) as { lab: string; main: string; accent: string }[])
  labColors[fam.lab] = { main: fam.main, accent: fam.accent }

const rarity = (power: number) => (power >= 390 ? "legendary" : power >= 320 ? "rare" : "common")

// display names, kept short enough for the card header
const display = (name: string) =>
  name
    .replace(/^claude-/, "claude ")
    .replace(/^gpt-/, "gpt ")
    .replace(/^gemini-/, "gemini ")
    .replace(/-/g, " ")

// the indexer is not caught up yet, so these are sample evolution badges for the showcase only
const sampleEvolution: Record<string, { stat: string; delta: number; since: string }> = {
  "claude-fable-5": { stat: "code", delta: 4, since: "sept 25" },
  "kimi-k3": { stat: "speed", delta: 7, since: "sept 26" },
  "deepseek-v4.1-flash": { stat: "cost", delta: 3, since: "sept 27" },
  "gemini-3.8-flash": { stat: "math", delta: -2, since: "sept 27" },
}

const cards = (stats.cards as StatCard[]).map(c => {
  const s = Object.fromEntries((stats.statOrder as string[]).map((k, i) => [k, c.stats[i]!]))
  const type = TYPES.reduce((best, t) => (s[t]! > s[best]! ? t : best), TYPES[0])
  return {
    id: c.id,
    name: c.name,
    display: display(c.name),
    lab: c.lab,
    colors: labColors[c.lab] ?? { main: "#888888", accent: "#dddddd" },
    stats: s,
    raw: c.raw,
    power: c.power,
    type,
    rarity: rarity(c.power),
    evolution: sampleEvolution[c.name] ?? null,
    art: {
      full: (tier: number) => `../lpc/out/tiers/${c.name}-t${tier}@8x.png`,
    },
  }
})

const marks = Object.fromEntries(
  Object.entries(logos).map(([lab, l]) => [lab, { colors: l.colors, badge: l.badge, mini: minis[lab] }]),
)

const out = `// generated by card/build-data.ts, do not edit
window.BENCHMON = ${JSON.stringify(
  {
    builtAt: stats.builtAt,
    statOrder: stats.statOrder,
    sources: stats.sources,
    cards: cards.map(({ art, ...rest }) => rest),
    marks,
  },
  null,
  1,
)}
`
writeFileSync(join(here, "data.js"), out)
console.log(`${cards.length} cards -> card/data.js`)
